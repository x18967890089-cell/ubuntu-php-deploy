#!/usr/bin/env bash
#
# deploy.sh — 一键把 PHP 站点部署到 Ubuntu/Debian 的 nginx + php-fpm
#
# 特性：幂等（重复执行只更新变化的部分）、不写死任何项目名/域名/凭据、
#       支持 --dry-run 先看要做什么、失败即停并给出下一步。
#
# 用法（root）：
#   sudo bash deploy.sh --app-dir /var/www/my-site --port 8080 --domain example.com
#   sudo bash deploy.sh --app-dir /var/www/my-site --dry-run
#
# 退出码：0 成功；1 参数/环境错误；2 依赖缺失；3 部署后自检失败
#
set -euo pipefail

VERSION="1.0.0"

# ---------------------------------------------------------------- 默认值
APP_DIR=""                 # 站点根目录（必填）
PORT="${PORT:-8080}"       # 监听端口
DOMAIN="${DOMAIN:-_}"      # server_name，默认不限定
PHP_VER="${PHP_VER:-}"     # 空 = 自动探测
WEBROOT="${WEBROOT:-public}"   # 站点根里的 web 目录名，空字符串表示 APP_DIR 本身
SITE_NAME="${SITE_NAME:-}"     # nginx 站点名，默认取 APP_DIR 的 basename
DB_DIR="${DB_DIR:-database}"   # 需要 www-data 可写的目录，相对 APP_DIR；空 = 不处理
DB_INIT="${DB_INIT:-}"         # 相对 APP_DIR 的初始化脚本，例如 init_db.php；空 = 跳过
HEALTH_PATH="${HEALTH_PATH:-/}" # 自检请求的路径
REQUIRED_EXT="${REQUIRED_EXT:-mbstring pdo_sqlite}"  # 必须存在的 PHP 扩展，空格分隔；空 = 不检查
CLIENT_MAX_BODY="${CLIENT_MAX_BODY:-32m}"
DRY_RUN=0
PRINT_CONFIG=0

C_OFF=$'\033[0m'; C_CYAN=$'\033[1;36m'; C_RED=$'\033[1;31m'; C_YEL=$'\033[1;33m'; C_GRN=$'\033[1;32m'

log()  { printf '%s[deploy]%s %s\n' "$C_CYAN" "$C_OFF" "$*"; }
ok()   { printf '%s  ok   %s %s\n' "$C_GRN" "$C_OFF" "$*"; }
warn() { printf '%s[warn]%s %s\n' "$C_YEL" "$C_OFF" "$*" >&2; }
die()  { printf '%s[error]%s %s\n' "$C_RED" "$C_OFF" "$*" >&2; exit "${2:-1}"; }

# run：dry-run 时只打印命令
run() {
  if [[ $DRY_RUN -eq 1 ]]; then printf '  + %s\n' "$*"; return 0; fi
  "$@"
}

# 生成 nginx 站点配置到 stdout（--print-config 与真实写入共用一份）
nginx_config() {
  cat <<NGINX
# generated by deploy.sh $VERSION — 可以手工修改，重新执行会覆盖
server {
    listen ${PORT};
    server_name ${DOMAIN};

    root ${WEB_ROOT};
    index index.php index.html;

    client_max_body_size ${CLIENT_MAX_BODY};

    # 隐藏文件（保留 ACME 校验）
    location ~ /\.(?!well-known) {
        deny all;
    }

    # 即使有人把数据库/源码放进 web 根，也不给下载
    location ~* \.(sqlite|sqlite3|db|sql|md|log|bak|env|ini)$ {
        deny all;
    }

    location / {
        try_files \$uri \$uri/ /index.php?\$query_string;
    }

    location ~ \.php\$ {
        include snippets/fastcgi-php.conf;
        fastcgi_pass unix:/run/php/php${PHP_VER}-fpm.sock;
    }
}
NGINX
}

usage() {
  cat <<'EOF'
deploy.sh — deploy a PHP site to nginx + php-fpm on Ubuntu/Debian (idempotent)

Usage:
  sudo bash deploy.sh --app-dir /var/www/my-site [options]

Options:
  --app-dir DIR      site directory on the server (required)
  --port PORT        listen port, default 8080
  --domain NAME      server_name, default _ (any host)
  --php VER          PHP version, e.g. 8.2; default: auto-detect
  --webroot DIR      web root inside app dir, default "public"; "" = app dir
  --site NAME        nginx site name, default: basename of app dir
  --db-dir DIR       dir to chown to www-data, default "database"; "" = skip
  --db-init FILE     PHP init script relative to app dir (skipped if absent)
  --health PATH      path used for the post-deploy check, default /
  --ext "A B"        required PHP extensions, default "mbstring pdo_sqlite"
  --client-max BODY  nginx client_max_body_size, default 32m
  --print-config     print the generated nginx config and exit
  --dry-run          print the plan, change nothing
  -h, --help         show this help
  -V, --version      show version

Exit codes: 0 ok, 1 bad arguments/environment, 2 missing dependency, 3 failed health check
EOF
}

# ---------------------------------------------------------------- 参数解析
while [[ $# -gt 0 ]]; do
  case "$1" in
    --app-dir)      APP_DIR="${2:-}"; shift 2 ;;
    --port)         PORT="${2:-}"; shift 2 ;;
    --domain)       DOMAIN="${2:-}"; shift 2 ;;
    --php)          PHP_VER="${2:-}"; shift 2 ;;
    --webroot)      WEBROOT="${2:-}"; shift 2 ;;
    --site)         SITE_NAME="${2:-}"; shift 2 ;;
    --db-dir)       DB_DIR="${2:-}"; shift 2 ;;
    --db-init)      DB_INIT="${2:-}"; shift 2 ;;
    --health)       HEALTH_PATH="${2:-}"; shift 2 ;;
    --ext)          REQUIRED_EXT="${2:-}"; shift 2 ;;
    --client-max)   CLIENT_MAX_BODY="${2:-}"; shift 2 ;;
    --print-config) PRINT_CONFIG=1; shift ;;
    --dry-run)      DRY_RUN=1; shift ;;
    -h|--help)      usage; exit 0 ;;
    -V|--version)   echo "deploy.sh $VERSION"; exit 0 ;;
    *)              die "未知参数：$1（用 --help 看用法）" ;;
  esac
done

[[ -n "$APP_DIR" ]] || die "必须指定 --app-dir（例如 /var/www/my-site）"
[[ "$APP_DIR" == /* ]] || die "--app-dir 必须是绝对路径，收到：$APP_DIR"
[[ "$PORT" =~ ^[0-9]+$ ]] || die "--port 必须是数字，收到：$PORT"
(( PORT >= 1 && PORT <= 65535 )) || die "--port 超出范围：$PORT"
[[ -z "$PHP_VER" || "$PHP_VER" =~ ^[0-9]+\.[0-9]+$ ]] || die "--php 形如 8.2，收到：$PHP_VER"
SITE_NAME="${SITE_NAME:-$(basename "$APP_DIR")}"
WEB_ROOT="${APP_DIR}${WEBROOT:+/$WEBROOT}"

log "deploy.sh $VERSION"
log "app dir   : $APP_DIR"
log "web root  : $WEB_ROOT"
log "listen    : ${PORT}    server_name: ${DOMAIN}"
log "php       : ${PHP_VER:-auto}    ext: ${REQUIRED_EXT:-none}"
[[ $DRY_RUN -eq 1 ]] && warn "dry-run：只打印命令，不做任何修改"
[[ $PRINT_CONFIG -eq 1 ]] && log "--print-config：只输出配置，不改动系统"

# ---------------------------------------------------------------- 前置检查
if [[ $DRY_RUN -eq 0 && $PRINT_CONFIG -eq 0 ]]; then
  [[ $EUID -eq 0 ]] || die "请用 root 执行：sudo bash $0 --app-dir $APP_DIR"
  command -v apt-get >/dev/null 2>&1 || die "只支持 Debian/Ubuntu 系（找不到 apt-get）" 2
elif [[ $DRY_RUN -eq 1 ]]; then
  command -v apt-get >/dev/null 2>&1 || warn "本机没有 apt-get —— dry-run 仅打印计划，不做实际安装"
fi

if [[ $DRY_RUN -eq 0 && $PRINT_CONFIG -eq 0 ]]; then
  [[ -d "$APP_DIR" ]] || die "目录不存在：$APP_DIR（先把代码上传到服务器）"
  [[ -n "$WEBROOT" && -d "$WEB_ROOT" ]] || warn "没找到 web 目录：$WEB_ROOT —— 确认 --webroot 是否写对"
  [[ -f "$WEB_ROOT/index.php" ]] || warn "web 目录里没有 index.php，站点可能 404"
fi

# ---------------------------------------------------------------- PHP 版本
detect_php() {
  [[ -n "$PHP_VER" ]] && return 0
  local v=""
  if command -v php >/dev/null 2>&1; then
    v="$(php -r 'echo PHP_MAJOR_VERSION.".".PHP_MINOR_VERSION;' 2>/dev/null || true)"
  fi
  if [[ -z "$v" ]]; then
    v="$(apt-cache show php-fpm 2>/dev/null | awk -F'[:-]' '/^Version: php/{print $3; exit}' || true)"
  fi
  if [[ -z "$v" && ( $DRY_RUN -eq 1 || $PRINT_CONFIG -eq 1 ) ]]; then
    v="8.1"
    warn "无法探测 PHP 版本，按 $v 演示（真实执行请用 --php 指定）"
  fi
  [[ -n "$v" ]] || die "无法探测 PHP 版本，请用 --php 8.2 指定" 2
  PHP_VER="$v"
  log "探测到 PHP 版本：$PHP_VER"
}
detect_php

if [[ $PRINT_CONFIG -eq 1 ]]; then
  nginx_config
  exit 0
fi

if [[ $DRY_RUN -eq 0 && $PRINT_CONFIG -eq 0 ]]; then
  apt-cache show "php${PHP_VER}-fpm" >/dev/null 2>&1 \
    || die "软件源里没有 php${PHP_VER}-fpm —— 换一个 --php 版本，或先添加 ondrej/php 源" 2
fi

# ---------------------------------------------------------------- 安装依赖
log "安装 nginx 与 PHP 组件…"
export DEBIAN_FRONTEND=noninteractive
run apt-get update -qq
run apt-get install -y -qq \
  nginx \
  "php${PHP_VER}-fpm" \
  "php${PHP_VER}-cli" \
  "php${PHP_VER}-sqlite3" \
  "php${PHP_VER}-mbstring" \
  "php${PHP_VER}-curl" \
  "php${PHP_VER}-xml" \
  unzip \
  curl

# ---------------------------------------------------------------- 扩展自检
if [[ $DRY_RUN -eq 0 && -n "$REQUIRED_EXT" ]]; then
  log "检查 PHP 扩展…"
  modules="$(php -m 2>/dev/null || true)"
  for ext in $REQUIRED_EXT; do
    if grep -qi "^${ext}$" <<<"$modules"; then
      ok "$ext"
    else
      die "PHP 扩展 $ext 未启用（尝试：apt-get install php${PHP_VER}-$(echo "$ext" | tr '_' '-')）" 2
    fi
  done
  php -r 'exit(version_compare(PHP_VERSION, "8.0.0", ">=") ? 0 : 1);' \
    || die "PHP 版本低于 8.0（本项目按 8.0+ 编写）" 2
fi

# ---------------------------------------------------------------- 目录权限
if [[ -n "$DB_DIR" ]]; then
  log "准备可写目录：$APP_DIR/$DB_DIR"
  run mkdir -p "$APP_DIR/$DB_DIR"
  run chown -R www-data:www-data "$APP_DIR/$DB_DIR"
  run chmod 775 "$APP_DIR/$DB_DIR"
fi

# ---------------------------------------------------------------- 可选初始化
if [[ -n "$DB_INIT" ]]; then
  if [[ -f "$APP_DIR/$DB_INIT" ]]; then
    log "执行初始化脚本：$DB_INIT"
    if [[ $DRY_RUN -eq 1 ]]; then
      printf '  + sudo -u www-data php %s\n' "$APP_DIR/$DB_INIT"
    else
      ( cd "$APP_DIR" && sudo -u www-data php "$DB_INIT" ) || die "初始化脚本执行失败：$DB_INIT"
    fi
  else
    log "跳过初始化：找不到 $APP_DIR/$DB_INIT"
  fi
fi

# ---------------------------------------------------------------- nginx 站点
NGINX_CONF="/etc/nginx/sites-available/${SITE_NAME}"
log "写 nginx 站点：$NGINX_CONF"

TMP_CONF="$(mktemp)"
trap 'rm -f "$TMP_CONF"' EXIT
nginx_config > "$TMP_CONF"

if [[ $DRY_RUN -eq 1 ]]; then
  printf '  + install nginx config (%s bytes) -> %s\n' "$(wc -c < "$TMP_CONF" | tr -d ' ')" "$NGINX_CONF"
elif [[ -f "$NGINX_CONF" ]] && cmp -s "$TMP_CONF" "$NGINX_CONF"; then
  ok "nginx 配置无变化"
else
  [[ -f "$NGINX_CONF" ]] && cp -a "$NGINX_CONF" "${NGINX_CONF}.bak"
  install -m 0644 "$TMP_CONF" "$NGINX_CONF"
  ok "已写入（旧配置备份为 ${NGINX_CONF}.bak）"
fi

run ln -sfn "$NGINX_CONF" "/etc/nginx/sites-enabled/${SITE_NAME}"

if [[ -e /etc/nginx/sites-enabled/default ]]; then
  log "停用默认站点（备份到 /etc/nginx/sites-enabled/default.bak）"
  run mv /etc/nginx/sites-enabled/default "/etc/nginx/sites-enabled/default.bak"
fi

if [[ $DRY_RUN -eq 1 ]]; then
  printf '  + nginx -t\n'
else
  nginx -t || die "nginx 配置检查失败，站点未启用（旧配置仍在 ${NGINX_CONF}.bak）"
fi

run systemctl enable --now nginx
run systemctl enable --now "php${PHP_VER}-fpm"
run systemctl reload nginx

# ---------------------------------------------------------------- 防火墙
if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
  log "ufw 已启用，放行 ${PORT}/tcp"
  run ufw allow "${PORT}/tcp" >/dev/null
else
  log "ufw 未启用（云厂商安全组需自行放行 ${PORT} 端口）"
fi

# ---------------------------------------------------------------- 自检
if [[ $DRY_RUN -eq 1 ]]; then
  printf '  + curl -o /dev/null -w "%%{http_code}" http://127.0.0.1:%s%s\n' "$PORT" "$HEALTH_PATH"
  echo
  log "dry-run 结束：以上是全部动作，未修改系统"
  exit 0
fi

log "本机自检：http://127.0.0.1:${PORT}${HEALTH_PATH}"
CODE="$(curl -s -o /dev/null -m 10 -w '%{http_code}' "http://127.0.0.1:${PORT}${HEALTH_PATH}" || echo 000)"
if [[ "$CODE" =~ ^[23][0-9][0-9]$ ]]; then
  ok "HTTP ${CODE}"
else
  warn "HTTP ${CODE} —— 看 nginx 日志：/var/log/nginx/error.log"
  exit 3
fi

IP="$(curl -s -m 3 https://ifconfig.me 2>/dev/null || echo '<服务器IP>')"

cat <<DONE

============================================================
 部署完成

   本机：  http://127.0.0.1:${PORT}${HEALTH_PATH}
   外网：  http://${IP}:${PORT}${HEALTH_PATH}   （安全组要放行 ${PORT}）

   下一步：
     1) 备案/域名就绪后，用 80 端口和域名重跑：
        sudo bash deploy.sh --app-dir ${APP_DIR} --port 80 --domain ${DOMAIN/_\*your-domain.com}
     2) 上 HTTPS：
        apt-get install -y certbot python3-certbot-nginx
        certbot --nginx -d your-domain.com
     3) 排查：
        systemctl status nginx --no-pager
        tail -n 50 /var/log/nginx/error.log
        ls -ld ${APP_DIR}${DB_DIR:+/$DB_DIR}
============================================================
DONE
